"""Builds packages/core/src/geo/egm96-grid.ts: EGM96 geoid heights on a 1° grid.

Source: the 15' EGM96 grid (NGA, public domain) as packed in the npm package
egm96-universal 1.1.1 (MIT): a base64 string of big-endian int16 centimetres, 721 rows from
90°N, 1440 columns from 0°E. Every 4th row and column is kept (181 × 360, about 130 KB);
bilinear on that grid is within 0.1 m of the full grid at the median and 1.8 m at the 99th
percentile, well inside what the ground fit needs.

  npm pack egm96-universal@1.1.1 && tar xzf egm96-universal-1.1.1.tgz
  python3 scripts/build-egm96-grid.py package/dist/egm96-universal.esm.js
"""
import array, base64, re, sys

src = open(sys.argv[1]).read()
raw = base64.b64decode(re.search(r'var data = "([^"]+)"', src).group(1))
full = array.array("h")
full.frombytes(raw)
if sys.byteorder == "little":
    full.byteswap()  # source is big-endian
COLS = 1440
grid = array.array("h", [full[r * 4 * COLS + c * 4] for r in range(181) for c in range(360)])
if sys.byteorder != "little":
    grid.byteswap()
b64 = base64.b64encode(grid.tobytes()).decode()
lines = [b64[i : i + 120] for i in range(0, len(b64), 120)]
body = "\n".join(f'  "{l}"{" +" if i < len(lines) - 1 else ";"}' for i, l in enumerate(lines))
out = f"""// Generated by scripts/build-egm96-grid.py. Do not edit.
// EGM96 geoid heights (NGA, public domain) on a 1° grid: 181 rows from 90°N to 90°S, 360
// columns from 0°E eastward, little-endian int16 centimetres, base64.
export const EGM96_GRID_1DEG =
{body}
"""
open("packages/core/src/geo/egm96-grid.ts", "w").write(out)
