// Production gap 10: the list of third-party licences shipped with VIEWER.
//
// Reads every package the web app and the server use at run time (`pnpm licenses list --prod`)
// and writes THIRD_PARTY_LICENSES.md: a table of packages, versions and licences, then each
// package's own licence text. It fails (exit 1) on a licence outside the allowed list below.
//
//   node scripts/licenses.cjs          write THIRD_PARTY_LICENSES.md
//   node scripts/licenses.cjs --check  fail if it is out of date or a licence is not allowed (CI)
//
// Data and imagery that ship with the samples are listed in docs/DATA_SOURCES.md.
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "THIRD_PARTY_LICENSES.md");

// Permissive licences, plus OFL for the fonts and MPL-2.0 (file-level copyleft; the files are
// shipped unmodified).
const ALLOWED = new Set(["MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "0BSD", "Apache-2.0", "Zlib", "CC0-1.0", "CC-BY-4.0", "BlueOak-1.0.0", "Python-2.0", "Unlicense", "WTFPL", "OFL-1.1", "MPL-2.0"]);
// Packages allowed under a licence that is not on the list, and why.
const EXCEPTIONS = {
  "@img/sharp-libvips-linux-x64": "LGPL-3.0-or-later. libvips is a separate shared library that sharp loads at run time, unmodified; it can be replaced, as the LGPL requires. Used by the server's glTF tools for textures.",
  "@img/sharp-libvips-linuxmusl-x64": "As @img/sharp-libvips-linux-x64.",
  "@img/sharp-libvips-linux-arm64": "As @img/sharp-libvips-linux-x64.",
  "@img/sharp-libvips-darwin-arm64": "As @img/sharp-libvips-linux-x64.",
  "@img/sharp-win32-x64": "As @img/sharp-libvips-linux-x64 (the Windows build of sharp carries libvips inside).",
};

/** True when an SPDX expression is satisfied by the allowed list (OR: any side, AND: both). */
function allowed(expr) {
  const e = expr.trim().replace(/^\((.*)\)$/, "$1");
  if (/ OR /i.test(e)) return e.split(/ OR /i).some(allowed);
  if (/ AND /i.test(e)) return e.split(/ AND /i).every(allowed);
  return ALLOWED.has(e);
}

function licenceText(dir) {
  try {
    const f = fs.readdirSync(dir).find((n) => /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i.test(n) || /^licen[cs]e[-.]/i.test(n));
    return f ? fs.readFileSync(path.join(dir, f), "utf8").trim() : null;
  } catch {
    return null;
  }
}

const json = execFileSync("pnpm", ["licenses", "list", "--prod", "--json", "-r"], { cwd: ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
const byLicence = JSON.parse(json);
const pkgs = [];
for (const [licence, list] of Object.entries(byLicence))
  for (const p of list) for (const v of p.versions) pkgs.push({ name: p.name, version: v, licence, homepage: p.homepage ?? "", dir: p.paths[p.versions.indexOf(v)] ?? p.paths[0] });
pkgs.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));

const refused = pkgs.filter((p) => !allowed(p.licence) && !EXCEPTIONS[p.name]);
const excepted = pkgs.filter((p) => !allowed(p.licence) && EXCEPTIONS[p.name]);

const md = [
  "# Third-party licences",
  "",
  "VIEWER ships with the open-source packages below, used by the web app and the server at run time. This file is generated by `node scripts/licenses.cjs` from the installed packages; do not edit it by hand. Sample data and imagery are listed in `docs/DATA_SOURCES.md`.",
  "",
  `${pkgs.length} packages.`,
  "",
  "| Package | Version | Licence |",
  "|---|---|---|",
  ...pkgs.map((p) => `| ${p.homepage ? `[${p.name}](${p.homepage})` : p.name} | ${p.version} | ${p.licence} |`),
  "",
  ...(excepted.length ? ["## Licences outside the usual list", "", ...excepted.map((p) => `- **${p.name} ${p.version}** (${p.licence}): ${EXCEPTIONS[p.name]}`), ""] : []),
  "## Licence texts",
  "",
  ...pkgs.flatMap((p) => {
    const text = licenceText(p.dir);
    return [`### ${p.name} ${p.version}`, "", text ? "```text\n" + text.replace(/```/g, "ʼʼʼ") + "\n```" : `${p.licence}. The package ships no licence file; the licence's standard text applies.`, ""];
  }),
].join("\n");

let failed = false;
if (refused.length) {
  failed = true;
  console.error("Licences not on the allowed list (scripts/licenses.cjs):");
  for (const p of refused) console.error(`  ${p.name} ${p.version}: ${p.licence}`);
}
if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== md) {
    failed = true;
    console.error("THIRD_PARTY_LICENSES.md is out of date: run node scripts/licenses.cjs and commit it.");
  }
} else {
  fs.writeFileSync(OUT, md);
  console.log(`Wrote ${path.relative(ROOT, OUT)}: ${pkgs.length} packages, ${excepted.length} allowed by exception.`);
}
if (failed) process.exit(1);
if (process.argv.includes("--check")) console.log(`Licences OK: ${pkgs.length} packages.`);
