export type Strings = typeof en;

type Params = Record<string, string | number>;
/** Looks a key up in the English strings, with {{name}} values and _one/_other plurals by count. */
function lookup(key: string, params: Params): string | undefined {
  const parts = key.split(".");
  const last = parts.pop()!;
  let node: unknown = en;
  for (const p of parts) node = (node as Record<string, unknown> | undefined)?.[p];
  const o = node as Record<string, unknown> | undefined;
  const plural = typeof params.count === "number" ? o?.[`${last}_${params.count === 1 ? "one" : "other"}`] : undefined;
  const s = plural ?? o?.[last];
  return typeof s === "string" ? s.replace(/\{\{(\w+)\}\}/g, (_, k: string) => String(params[k] ?? "")) : undefined;
}

/**
 * The English text for an i18n key. Code that runs outside the interface (the model checks, the
 * server) writes English with it and keeps the key, so the app can show the same message in
 * the interface language.
 */
export function english(key: string, params: Params = {}): string {
  return lookup(key, params) ?? key;
}
/** True when the English strings have this key (or its plural forms). */
export function hasEnglish(key: string): boolean {
  return lookup(key, { count: 2 }) !== undefined;
}
